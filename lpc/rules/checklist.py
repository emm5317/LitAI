"""Write docs/RULES_CHECKLIST.md: every rule entry with its citation and period, for
checking against the source texts. Tick an entry by setting `verified: true` in its
YAML file once it matches.

    python -m lpc.rules.checklist
"""

from __future__ import annotations

import json
from pathlib import Path

from .engine import load_rulesets

SOURCES = json.loads((Path(__file__).resolve().parent / "sources.json").read_text(encoding="utf-8"))


def render() -> str:
    by_id = {s["id"]: s for s in SOURCES["sources"]}
    lines = [
        "# Rules verification checklist",
        "",
        "Generated by `python -m lpc.rules.checklist`. Check each period against the source text,",
        "then set `verified: true` on the entry in `lpc/rules/data/rulesets/`. Unverified entries",
        "show a warning in the app every time they are used.",
        "",
    ]
    for rs in load_rulesets().values():
        lines.append(f"## {rs.name} (`{rs.id}`)")
        lines.append("")
        for sid in rs.sources:
            src = by_id.get(sid)
            if src:
                lines.append(f"Source: [{src['title']}]({src['landing']}). {src['version_note']}")
        lines.append(f"Counting: `{rs.counting}`. Holidays: {', '.join(rs.holidays_all) or 'none'}"
                     + (f"; forward-only: {', '.join(rs.holidays_forward_only)}" if rs.holidays_forward_only else "")
                     + ".")
        if rs.base:
            lines.append(f"Inherits: {', '.join(rs.base)}.")
        lines.append("")
        if not rs.entries:
            lines.append("_No entries yet._")
            lines.append("")
            continue
        lines.append("| ✓ | Entry | Citation | Period | Trigger |")
        lines.append("| --- | --- | --- | --- | --- |")
        for e in rs.entries:
            period = f"{e.days} days" if e.days is not None else f"{e.months} months"
            period += " before" if e.direction == "before" else ""
            if e.service_applies:
                period += " (+ service rule)"
            mark = "x" if e.verified else " "
            lines.append(f"| [{mark}] | {e.title} | {e.cite} | {period} | {e.trigger} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    out = Path("docs/RULES_CHECKLIST.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
